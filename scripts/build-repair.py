#!/usr/bin/env python3
"""Validate and package the repair site and the selected portfolio page."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'frontend' / 'public'
OUTPUT = ROOT / 'dist'
PAGES = ('index.html', 'services.html', 'prices.html', 'about.html', 'contact.html', 'portfolio.html')

class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.refs, self.ids, self.labels, self.fields = [], [], [], []
        self.heading_count = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            self.ids.append(attrs['id'])
        if tag == 'h1':
            self.heading_count += 1
        if tag == 'label':
            self.labels.append(attrs.get('for'))
        if tag in ('input', 'textarea', 'select'):
            self.fields.append(attrs.get('id'))
        if tag == 'img' and not all(attrs.get(key) for key in ('alt', 'width', 'height')):
            raise ValueError('Images need alt text and explicit dimensions')
        for key in ('src', 'href'):
            if key in attrs:
                self.refs.append(attrs[key])


def main():
    pages, assets = {}, set()
    for name in PAGES:
        parsed = Page()
        source = (PUBLIC / name).read_text()
        parsed.feed(source)
        if parsed.heading_count != 1 or len(parsed.ids) != len(set(parsed.ids)):
            raise ValueError(f'Invalid page structure: {name}')
        if not set(parsed.fields).issubset(parsed.labels):
            raise ValueError(f'Unlabelled form control: {name}')
        pages[name] = parsed

    for name, parsed in pages.items():
        for ref in parsed.refs:
            url = urlsplit(ref)
            if url.scheme or url.netloc:
                continue
            relative = Path(unquote(url.path)) if url.path else Path(name)
            target = (PUBLIC / relative).resolve()
            if not target.is_relative_to(PUBLIC.resolve()) or not target.is_file():
                raise ValueError(f'Missing or invalid local link in {name}: {ref}')
            if url.fragment and relative.name in pages:
                if url.fragment not in pages[relative.name].ids:
                    raise ValueError(f'Missing anchor in {name}: {ref}')
            if relative.as_posix() not in PAGES:
                assets.add(relative)

    # Only replace the generated directory owned by this script.
    if OUTPUT.exists():
        if not (OUTPUT / '.repair-build').is_file():
            raise ValueError('Refusing to replace a dist directory not created by this build')
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    for relative in [Path(name) for name in PAGES] + sorted(assets):
        target = OUTPUT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(PUBLIC / relative, target)
    (OUTPUT / '.repair-build').write_text('Generated by scripts/build-repair.py\n')
    print(f'Repair site built: {len(PAGES)} pages, {len(assets)} assets. Links, headings, images, and form labels validated.')

if __name__ == '__main__':
    main()
